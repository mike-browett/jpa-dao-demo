package com.aixpertsoft.datastack.generator.gen;

import static com.aixpertsoft.datastack.generator.Names.snake;

import com.aixpertsoft.datastack.generator.ModelIndex;
import com.aixpertsoft.datastack.generator.ModelIndex.Entity;
import com.aixpertsoft.datastack.generator.ModelIndex.ToOne;
import com.aixpertsoft.datastack.generator.Types;
import com.aixpertsoft.datastack.generator.model.AttributeDef;
import com.aixpertsoft.datastack.generator.model.RelationDef;
import java.util.ArrayList;
import java.util.List;

/**
 * Liquibase changelog (formatted SQL, PostgreSQL) for the model: one changeset per table, one for the foreign keys.
 * Constraint names follow a fixed pattern so errors can be mapped to codes: uq_table_column, uq_table, ex_table_..., fk_table_column.
 *
 * <p>Prototype limitation: the changelog describes the schema from scratch. After changing tables in the model,
 * reset the development database, or add hand-written changesets to the custom changelog.
 */
public final class ChangelogGenerator {

    private final ModelIndex index;
    private final Output out;

    public ChangelogGenerator(ModelIndex index, Output out) {
        this.index = index;
        this.out = out;
    }

    public static String path(ModelIndex index) {
        return "db/changelog/" + index.id() + "/generated.sql";
    }

    public static String uniqueColumn(String table, String column) {
        return "uq_" + table + "_" + column;
    }

    public void generate() {
        if (!index.model().database().generateChangelog()) return;
        String model = index.model().id();
        StringBuilder sql = new StringBuilder("""
                --liquibase formatted sql
                -- GENERATED by datastack-generator from model.json. Do not edit: custom changesets go in the custom changelog.
                -- Tables live in schema %s (one schema per model, so models can share a database).
                """.formatted(index.schema()));
        List<String> foreignKeys = new ArrayList<>();
        for (Entity e : index.entities()) {
            if (!index.isRoot(e)) continue;
            String table = e.def().table();
            List<String> lines = new ArrayList<>();
            List<String> tail = new ArrayList<>();
            lines.add("id uuid PRIMARY KEY");
            boolean disc = index.hasDiscriminator(e);
            String discColumn = index.discriminatorColumn(e);
            if (disc) lines.add(discColumn + " varchar(30) NOT NULL");
            if (e.isIntersection()) {
                for (ToOne r : index.ownToOnes(e)) {
                    lines.add(r.column() + " uuid NOT NULL");
                    foreignKeys.add(fk(table, r.column(), index.table(r.target()), "CASCADE"));
                }
            }
            for (AttributeDef a : index.hierarchyAttributes(e)) {
                if (a.isJson()) continue;
                Entity owner = index.declaringEntity(e, a);
                String col = index.column(a);
                StringBuilder c = new StringBuilder(col + " " + Types.sql(a));
                if (a.isRequired() && owner == e) c.append(" NOT NULL");
                if (a.defaultValue() != null) c.append(" DEFAULT ").append(Types.sqlLiteral(a.defaultValue()));
                lines.add(c.toString());
                if ("enum".equals(a.type())) {
                    tail.add("CONSTRAINT ck_" + table + "_" + col + " CHECK (" + col + " IN ("
                            + String.join(", ", a.values().stream().map(Types::sqlLiteral).toList()) + "))");
                }
                if (a.min() != null || a.max() != null) {
                    String check = a.min() != null && a.max() != null ? col + " BETWEEN " + a.min() + " AND " + a.max()
                            : a.min() != null ? col + " >= " + a.min() : col + " <= " + a.max();
                    tail.add("CONSTRAINT ck_" + table + "_" + col + "_range CHECK (" + check + ")");
                }
                if (a.isUnique()) {
                    tail.add("CONSTRAINT " + uniqueColumn(table, col) + " UNIQUE (" + col + ")");
                }
                if (a.isRequired() && owner != e) {
                    tail.add("CONSTRAINT ck_" + table + "_" + col + "_required CHECK (" + discColumn + " <> '"
                            + index.discriminatorValue(owner) + "' OR " + col + " IS NOT NULL)");
                }
            }
            if (!index.hierarchyJson(e).isEmpty()) {
                lines.add("ext jsonb NOT NULL DEFAULT '{}'::jsonb");
            }
            for (ToOne r : index.hierarchyToOnes(e)) {
                if (e.isIntersection()) continue;
                lines.add(r.column() + " uuid");
                String onDelete = switch (r.relation().onDeleteFrom()) {
                    case "setNull" -> "SET NULL";
                    case "cascade" -> "CASCADE";
                    default -> "RESTRICT";
                };
                foreignKeys.add(fk(table, r.column(), index.table(r.target()), onDelete));
            }
            lines.add("version bigint NOT NULL DEFAULT 0");
            if (e.isIntersection()) {
                RelationDef r = e.intersectionOf();
                List<String> uniqueCols = r.intersection().unique().stream().map(u -> column(e, u)).toList();
                tail.add("CONSTRAINT uq_" + table + " UNIQUE (" + String.join(", ", uniqueCols) + ")");
            }
            lines.addAll(tail);

            sql.append("\n--changeset ").append(model).append(":table-").append(table).append('\n');
            sql.append("CREATE TABLE ").append(q(table)).append(" (\n  ").append(String.join(",\n  ", lines)).append("\n);\n");
            if (disc) {
                sql.append("CREATE INDEX ix_").append(table).append('_').append(discColumn).append(" ON ").append(q(table))
                   .append('(').append(discColumn).append(");\n");
            }
            if (e.isIntersection()) {
                for (RelationDef.UniqueWhere u : e.intersectionOf().intersection().uniqueWhere()) {
                    sql.append(exclusion(e, table, u));
                }
            }
        }
        if (!foreignKeys.isEmpty()) {
            sql.append("\n--changeset ").append(model).append(":foreign-keys\n");
            foreignKeys.forEach(sql::append);
        }
        out.generatedResource(path(index), sql.toString());
    }

    private String column(Entity link, String name) {
        RelationDef r = link.intersectionOf();
        if (name.equals("from")) return snake(r.from().object()) + "_id";
        if (name.equals("to")) return snake(r.to().object()) + "_id";
        return index.attribute(link, name).map(index::column).orElse(snake(name));
    }

    /** "At most one row per key where flag": an exclusion constraint, deferred to commit so rules can reorder freely. */
    private String exclusion(Entity link, String table, RelationDef.UniqueWhere u) {
        List<String> cols = u.columns().stream().map(c -> column(link, c)).toList();
        String[] where = u.where().split("=");
        String flag = column(link, where[0].trim());
        String condition = where[1].trim().equals("true") ? flag : "NOT " + flag;
        String name = exclusionName(table, cols);
        return "-- at most one row per (" + String.join(", ", cols) + ") where " + u.where() + "; checked at commit\n"
                + "ALTER TABLE " + q(table) + "\n  ADD CONSTRAINT " + name + "\n  EXCLUDE USING btree ("
                + String.join(", ", cols.stream().map(c -> c + " WITH =").toList()) + ") WHERE (" + condition + ")\n"
                + "  DEFERRABLE INITIALLY DEFERRED;\n";
    }

    static String exclusionName(String table, List<String> columns) {
        return "ex_" + table + "_" + String.join("_", columns);
    }

    /** Column names of a uniqueWhere, as used in its constraint name. */
    List<String> exclusionColumns(Entity link, RelationDef.UniqueWhere u) {
        return u.columns().stream().map(c -> column(link, c)).toList();
    }

    /** Schema-qualified table name. */
    private String q(String table) {
        return index.schema() + "." + table;
    }

    private String fk(String table, String column, String target, String onDelete) {
        return "ALTER TABLE " + q(table) + " ADD CONSTRAINT fk_" + table + "_" + column + " FOREIGN KEY (" + column
                + ") REFERENCES " + q(target) + "(id) ON DELETE " + onDelete + ";\n"
                + "CREATE INDEX ix_" + table + "_" + column + " ON " + q(table) + "(" + column + ");\n";
    }
}
